/** 未知分类不渲染空白方块：回退到通用文档图标。 */
export function categoryIcon(slug: string): LucideIcon {
  return CATEGORY_ICONS[slug] ?? FileText;
}

/** 顶栏配置只存 href，图标按 `/docs/{slug}` 反查；非文档链接（首页/AI）回退通用图标。 */
export function iconFromHref(href: string | undefined): LucideIcon {
  const match = href?.match(/^\/docs\/([a-z0-9-]+)/);
  return match ? categoryIcon(match[1]) : FileText;
}
